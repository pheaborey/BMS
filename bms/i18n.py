def translator(lang: str):
    index = {"en": 0, "vi": 1, "fr": 2}.get(lang, 0)

    def t(key: str, **kwargs) -> str:
        row = ROWS.get(key)
        if lang == "km":
            text = KHMER.get(key)
        elif row:
            text = row[index] or row[0]
        else:
            text = None
        if text is None:
            return key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError):
                return text
        return text

    return t
